# -------- main ---------------------------------------------------------------------


def main() -> int:
    primary = _find_primary_artifact()
    docs_pages = {
        "index.html": build_index(primary),
        "executive-summary.html": build_executive_summary(primary),
        "hypotheses.html": build_hypotheses(primary),
        "leaderboard.html": build_leaderboard(primary),
        "sources.html": build_sources(primary),
        "irregularities.html": build_irregularities(primary),
    }
    out_dir = ROOT / "docs"
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, html in docs_pages.items():
        (out_dir / name).write_text(html, encoding="utf-8")
    print(f"[docs] Wrote {len(docs_pages)} pages to {out_dir}", flush=True)

    # Also write root-level copies for the GitHub Pages root source.  When GitHub Pages
    # serves from the repository root (the default for project sites with no /docs
    # folder configured), the root .html files are what readers see.  When it serves
    # from /docs (the alternative), the docs/ copies are what readers see.  We write
    # both so the one-click download is unambiguous in either configuration.
    import re as _re
    root_pages = {}
    for name, body in docs_pages.items():
        html = body
        # When viewed from the repo root, "downloads/X.tif" lives at "docs/downloads/X.tif"
        # and "assets/site.css" lives at "docs/assets/site.css".  The relative link to
        # evidence/cotrain_reasoning.json from a docs page is "../evidence/..." which would
        # escape the repo root; we rewrite it to "evidence/..." for the root copy.
        html = _re.sub(r'href="downloads/', 'href="docs/downloads/', html)
        html = _re.sub(r'href="assets/', 'href="docs/assets/', html)
        html = html.replace('href="../evidence/', 'href="evidence/')
        root_pages[name] = html
    for name, html in root_pages.items():
        (ROOT / name).write_text(html, encoding="utf-8")
    print(f"[docs] Wrote {len(root_pages)} root-level copies for GitHub Pages root source", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())