# -------- helpers -----------------------------------------------------------------


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def _find_primary_artifact() -> dict | None:
    """Pick the most recent *.tif under docs/downloads/ that has a matching -audit.json."""
    dl = downloads_dir()
    audit_files = sorted(dl.glob("*-audit.json"))
    for af in reversed(audit_files):
        zeros = af.parent / af.name.replace("-audit.json", "-zeros.tif")
        if zeros.exists():
            return {
                "slug": af.stem.replace("-audit", ""),
                "zeros": zeros,
                "nan": af.parent / af.name.replace("-audit.json", "-nan.tif"),
                "audit": af,
            }
    return None


def _head(s: str, n: int = 60) -> str:
    s = re.sub(r"\s+", " ", s).strip()
    return (s[:n] + "...") if len(s) > n else s


