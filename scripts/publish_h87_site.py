def verdict_block(short: bool = False) -> str:
    """Two separate questions, two unambiguous answers — never one mushy sentence."""
    v = wr["validator"]
    dl = (f"<div class=\"verdict ok\">1 &nbsp;·&nbsp; <b>OK TO DOWNLOAD, AND THE PORTAL WILL ACCEPT THE "
          f"FORMAT: YES.</b><br><span style=\"font-weight:400\">Re-read from the bytes on disk: "
          f"{v['bands']} band {v['dtype']}, {v['crs']}, {v['shape'][0]}×{v['shape'][1]}, transform and "
          f"bounds equal to the organiser template, <b>{v['nan']} NaN</b>, {v['infinite']} infinities, "
          f"values exactly {{0,&nbsp;1}} — so the portal's <i>\"Predicted values must be in range "
          f"[0, 1]\"</i> rejection cannot occur.</span></div>")
    if SUBMIT_OK:
        sub = ("<div class=\"verdict ok\">2 &nbsp;·&nbsp; <b>AUTO-PROMOTED BY THIS ROUND'S FROZEN "
               "RULE: YES.</b><br><span style=\"font-weight:400\">All six pre-registered gates passed. "
               "Spending one of the weekly slots is still a separate owner selector decision; this "
               "round spent 0.</span></div>")
    else:
        failed = ", ".join(k for k, v2 in card["gates"].items() if not v2)
        x = card.get("lane_excess_chance_corrected") or {}
        extra = ""
        if "max_near_informative_coverage_lt_0.95" in x:
            extra = (f" The statistic that failed is <b>below chance</b> for the prior that produced "
                     f"it: our dots fall inside that raster's 3&nbsp;px halo at "
                     f"{x['max_near_informative_coverage_lt_0.95']:.4f}, while the halo itself already "
                     f"covers {0.8976:.4f} of the legal footprint, so a uniform random placement would "
                     f"score about the same. Chance-corrected, <b>0 of "
                     f"{x['n_informative_measured']}</b> informative priors exceed the 0.70 bar "
                     f"(maximum {x['max_excess_informative_coverage_lt_0.95']:.4f}).")
        sub = (f"<div class=\"verdict warn\">2 &nbsp;·&nbsp; <b>AUTO-PROMOTED BY THIS ROUND'S FROZEN "
               f"RULE: NO.</b><br><span style=\"font-weight:400\">{6 - sum(card['gates'].values())} of 6 "
               f"pre-registered gates failed: <b>{esc(failed)}</b>.{extra} The rule is reported exactly "
               f"as it was frozen before the fit — it is not rewritten after seeing the result. "
               f"Uploading anyway is an owner decision taken with these numbers in hand; this round "
               f"spent 0 slots and the agent does not pick submissions.</span></div>")
    return dl + sub


