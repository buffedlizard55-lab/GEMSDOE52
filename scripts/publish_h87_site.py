def load(p: Path):
    return json.loads(Path(p).read_text())


def esc(x) -> str:
    return html.escape(str(x))


def f6(x) -> str:
    return "—" if x is None else f"{float(x):.6f}"


def f4(x) -> str:
    return "—" if x is None else f"{float(x):.4f}"


