def holdout_table() -> str:
    rows = []
    for a in ARMS:
        s = card["holdout"]["scores"][a]
        star = " ★ primary" if a == "CCD" else (" (control)" if a in ("single_B", "random") else "")
        rows.append(f"<tr><td>{esc(a)}{star}</td><td class=\"n\">{f6(s['dti'])}</td>"
                    f"<td class=\"n\">[{f6(s['ci95'][0])}, {f6(s['ci95'][1])}]</td></tr>")
    pt = hold["promotion_test"]
    return ("<table><tr><th>arm</th><th>HOLDOUT-DTI</th><th>95% CI (paired cluster bootstrap)</th></tr>"
            + "".join(rows) + "</table>"
            + f"<p class=\"kv\">Paired <b>CCD − single_B</b> = <b>{f6(pt['delta'])}</b> "
              f"[{f6(pt['delta_ci95'][0])}, {f6(pt['delta_ci95'][1])}]; frozen non-inferiority rule "
              f"(point ≥ single_B − 0.020 and CI lower bound &gt; −0.040): "
              f"<b>{'PASS' if pt['noninferior'] else 'FAIL'}</b>. "
              f"Evaluator <code>{esc(hold['evaluator'])}</code>, "
              f"{hold['withheld_positive_px']:,} withheld positive pixels, "
              f"{hold['budget_per_fold']:,} dots per fold per arm.</p>"
              "<p class=\"muted\">A HOLDOUT-DTI is not a leaderboard score and never a projection. "
              "This instrument hides <i>catalogue</i> segments; the competition scores faults the "
              "catalogue lacks, and the measured rank correlation between this number and the public "
              "board is about −0.10 across this project's rounds.</p>")


def gates_table() -> str:
    labels = dict(format="GeoTIFF format / range validator",
                  uniqueness_not_identical="decoded pixels differ from every registry raster",
                  lane_surface_rank="lane: surface rank-correlation ≤ 0.90",
                  lane_dots_policy="lane: dot proximity vs informative priors ≤ 0.70",
                  not_the_union="output is not the union of the two views",
                  holdout_noninferior="holdout non-inferiority vs single_B")
    rows = "".join(f"<tr><td>{esc(labels.get(k, k))}</td><td>{'✅ PASS' if v else '❌ FAIL'}</td></tr>"
                   for k, v in card["gates"].items())
    return f"<table><tr><th>pre-registered gate</th><th>result</th></tr>{rows}</table>"


